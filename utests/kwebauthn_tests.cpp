//:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
/// an authenticator with one credential of the algorithm ES256
struct Authenticator
//:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
{
	KECKey  Key           { true };
	KString sCredentialID = kGetRandom(16);
	KString sAAGUID       = KString(16, '\x11');

	/// the public key as a COSE key
	KCBOR CoseKey() const
	{
		auto sPoint = Key.GetPublicKeyRaw();

		return KCBOR::Map()
			.Add( 1, 2)
			.Add( 3, -7)
			.Add(-1, 1)
			.Add(-2, KCBOR::Bytes(sPoint.Mid(1, 32)))
			.Add(-3, KCBOR::Bytes(sPoint.Mid(33, 32)));
	}
};

//:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
/// what the browser and the authenticator put into a response. A test changes
/// single values to get a response with one defect.
struct Setup
//:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
{
	// the client data
	KString  sType;                                  // empty: the type of the ceremony
	KString  sOrigin         { "https://example.org" };
	bool     bCrossOrigin    { false };
	KString  sTopOrigin;
	KString  sClientData;                            // if set, used instead of the JSON of the values above
	// the authenticator data
	KString  sRelyingPartyID { "example.org" };
	uint8_t  iFlags          { iUserPresent | iUserVerified };
	uint32_t iSignCount      { 0 };
	bool     bCredentialData { true };               // in a registration: with the credential and its flag
	KCBOR    PublicKey;                              // if set, used instead of the key of the authenticator
	KCBOR    Extensions;                             // if set, appended with the flag for extensions
	KString  sTrailingBytes;
	// the attestation object
	KString  sFormat         { "none" };
	KCBOR    Statement       { KCBOR::Map() };
	// the response
	KString  sResponseType   { "public-key" };
	KString  sRawID;                                 // if set, used instead of the ID of the credential
	KString  sUserHandle;
};

//-----------------------------------------------------------------------------
KString ClientData(KStringView sType, KStringView sChallenge, const Setup& setup)
//-----------------------------------------------------------------------------
{
	if (!setup.sClientData.empty())
	{
		return setup.sClientData;
	}

	KJSON jClientData;

	jClientData["type"]        = setup.sType.empty() ? sType : KStringView(setup.sType);
	jClientData["challenge"]   = sChallenge;
	jClientData["origin"]      = setup.sOrigin;
	jClientData["crossOrigin"] = setup.bCrossOrigin;

	if (!setup.sTopOrigin.empty())
	{
		jClientData["topOrigin"] = setup.sTopOrigin;
	}

	return jClientData.dump();
}

//-----------------------------------------------------------------------------
KString AuthenticatorData(const Authenticator& authenticator, const Setup& setup, bool bRegistration)
//-----------------------------------------------------------------------------
{
	bool    bCredentialData = bRegistration && setup.bCredentialData;
	uint8_t iFlags          = setup.iFlags;

	if (bCredentialData)
	{
		iFlags |= iAttestedData;
	}

	if (!setup.Extensions.IsNull())
	{
		iFlags |= iExtensions;
	}

	KString sData = KSHA256(setup.sRelyingPartyID).Digest();

	sData += static_cast<char>(iFlags);
	sData += static_cast<char>(static_cast<uint8_t>(setup.iSignCount >> 24));
	sData += static_cast<char>(static_cast<uint8_t>(setup.iSignCount >> 16));
	sData += static_cast<char>(static_cast<uint8_t>(setup.iSignCount >>  8));
	sData += static_cast<char>(static_cast<uint8_t>(setup.iSignCount      ));

	if (bCredentialData)
	{
		sData += authenticator.sAAGUID;
		sData += static_cast<char>(static_cast<uint8_t>(authenticator.sCredentialID.size() >> 8));
		sData += static_cast<char>(static_cast<uint8_t>(authenticator.sCredentialID.size()     ));
		sData += authenticator.sCredentialID;
		sData += setup.PublicKey.IsNull() ? authenticator.CoseKey().Serialize() : setup.PublicKey.Serialize();
	}

	if (!setup.Extensions.IsNull())
	{
		sData += setup.Extensions.Serialize();
	}

	sData += setup.sTrailingBytes;

	return sData;
}

//-----------------------------------------------------------------------------
/// the response of navigator.credentials.create()
KJSON Register(const Authenticator& authenticator, KStringView sChallenge, const Setup& setup = Setup{})
//-----------------------------------------------------------------------------
{
	auto Attestation = KCBOR::Map()
		.Add("fmt"     , setup.sFormat)
		.Add("attStmt" , setup.Statement)
		.Add("authData", KCBOR::Bytes(AuthenticatorData(authenticator, setup, true)));

	KJSON jResponse;

	jResponse["type"]  = setup.sResponseType;
	jResponse["id"]    = KBase64Url::Encode(authenticator.sCredentialID);
	jResponse["rawId"] = KBase64Url::Encode(setup.sRawID.empty() ? authenticator.sCredentialID : setup.sRawID);
	jResponse["response"]["clientDataJSON"]    = KBase64Url::Encode(ClientData("webauthn.create", sChallenge, setup));
	jResponse["response"]["attestationObject"] = KBase64Url::Encode(Attestation.Serialize());
	jResponse["response"]["transports"]        = KJSON::array({ "internal", "hybrid" });

	return jResponse;
}

//-----------------------------------------------------------------------------
/// the response of navigator.credentials.get()
KJSON Login(const Authenticator& authenticator, KStringView sChallenge, const Setup& setup = Setup{})
//-----------------------------------------------------------------------------
{
	auto sClientData = ClientData("webauthn.get", sChallenge, setup);
	auto sAuthData   = AuthenticatorData(authenticator, setup, false);
	auto sSignature  = KECSign().Sign(authenticator.Key, sAuthData + KSHA256(sClientData).Digest(), KECSign::Format::Der);

	KJSON jResponse;

	jResponse["type"]  = setup.sResponseType;
	jResponse["id"]    = KBase64Url::Encode(authenticator.sCredentialID);
	jResponse["rawId"] = KBase64Url::Encode(setup.sRawID.empty() ? authenticator.sCredentialID : setup.sRawID);
	jResponse["response"]["clientDataJSON"]    = KBase64Url::Encode(sClientData);
	jResponse["response"]["authenticatorData"] = KBase64Url::Encode(sAuthData);
	jResponse["response"]["signature"]         = KBase64Url::Encode(sSignature);

	if (!setup.sUserHandle.empty())
	{
		jResponse["response"]["userHandle"] = KBase64Url::Encode(setup.sUserHandle);
	}

	return jResponse;
}

//-----------------------------------------------------------------------------
/// registers the credential of an authenticator with a valid response
KWebAuthn::Credential Registered(const KWebAuthn& WebAuthn, const Authenticator& authenticator, const Setup& setup = Setup{})
//-----------------------------------------------------------------------------
{
	KString sChallenge;
	auto    jOptions = WebAuthn.RegistrationOptions({ "handle", "jdoe", "John Doe" }, sChallenge);

	KWebAuthn::Credential Credential;

	bool bRegistered = WebAuthn.VerifyRegistration(Register(authenticator, sChallenge, setup), sChallenge, Credential);

	INFO    ( WebAuthn.Error() );
	REQUIRE ( bRegistered      );

	return Credential;
}

//:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
/// a pair of ceremonies from the test vectors of the WebAuthn specification
/// (Level 3, section 16), all values in hexadecimal
struct Vector
//:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
{
	KStringView sName;
	KStringView sFormat;
	bool        bSupported;
	KStringView sCredentialID;
	KStringView sRegistrationChallenge;
	KStringView sRegistrationClientData;
	KStringView sAttestationObject;
	KStringView sLoginChallenge;
	KStringView sAuthenticatorData;
	KStringView sLoginClientData;
	KStringView sSignature;

	KJSON RegistrationResponse() const
	{
		KJSON jResponse;

		jResponse["type"]  = "public-key";
		jResponse["id"]    = KBase64Url::Encode(kUnHex(sCredentialID));
		jResponse["rawId"] = KBase64Url::Encode(kUnHex(sCredentialID));
		jResponse["response"]["clientDataJSON"]    = KBase64Url::Encode(kUnHex(sRegistrationClientData));
		jResponse["response"]["attestationObject"] = KBase64Url::Encode(kUnHex(sAttestationObject));

		return jResponse;
	}

	KJSON LoginResponse() const
	{
		KJSON jResponse;

		jResponse["type"]  = "public-key";
		jResponse["id"]    = KBase64Url::Encode(kUnHex(sCredentialID));
		jResponse["rawId"] = KBase64Url::Encode(kUnHex(sCredentialID));
		jResponse["response"]["clientDataJSON"]    = KBase64Url::Encode(kUnHex(sLoginClientData));
		jResponse["response"]["authenticatorData"] = KBase64Url::Encode(kUnHex(sAuthenticatorData));
		jResponse["response"]["signature"]         = KBase64Url::Encode(kUnHex(sSignature));

		return jResponse;
	}

	/// the flags of the authenticator data of the registration, which follow the hash of the relying party ID
	uint8_t RegistrationFlags() const
	{
		auto sObject = kUnHex(sAttestationObject);
		auto iPos    = sObject.find(KSHA256("example.org").Digest());

		return (iPos == KString::npos) ? 0 : static_cast<uint8_t>(sObject[iPos + 32]);
	}

	uint8_t LoginFlags() const
	{
		return static_cast<uint8_t>(kUnHex(sAuthenticatorData)[32]);
	}
};

